const EN_PATTERNS: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
  [/^(\d+) peça$/, (m) => `${m[1]} piece`],
  [/^(\d+) peças$/, (m) => `${m[1]} pieces`],
  [/^Frete: (R\$\s?[\d.,]+)$/, (m) => `Shipping: ${m[1]}`],
  [/^Esta seleção com frete: (R\$\s?[\d.,]+)$/, (m) => `Selection total with shipping: ${m[1]}`],
  [/^Abrir sacola com (\d+) item$/, (m) => `Open bag with ${m[1]} item`],
  [/^Abrir sacola com (\d+) itens$/, (m) => `Open bag with ${m[1]} items`],
  [/^Ver resultados para “(.+)”$/, (m) => `View results for “${m[1]}”`],
  [/^Buscar “(.+)” na coleção$/, (m) => `Search “${m[1]}” in the collection`],
];

export function translateExactText(value: string, locale: SiteLocale) {
  if (locale !== 'en') return value;
  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  const core = value.trim();
  if (!core) return value;
  const exact = EN_TEXT[core];
  if (exact) return `${leading}${exact}${trailing}`;
  for (const [pattern, render] of EN_PATTERNS) {
    const match = core.match(pattern);
    if (match) return `${leading}${render(match)}${trailing}`;
  }
  return value;
}

export function getEnglishText(value: string) {
  return EN_TEXT[value] ?? value;
}
